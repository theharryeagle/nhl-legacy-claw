ReadbackResolveMode CommandProcessor::GetReadbackResolveMode(
    bool legacy_readback_resolve_enabled) const {
  // NHL debug knob: NHL_VK_READBACK_MODE={none,fast,some,full} overrides the
  // configured resolve-readback mode at runtime so the per-resolve GPU sync stall
  // (kFull) can be A/B'd against the delayed/double-buffered modes (kFast/kSome).
  // Unset = no override. Cached on first read (single CP worker thread). See also
  // the size-gated NHL_VK_READBACK_MAX_LEN in the Vulkan IssueCopy readback path,
  // which is the shipping lever (keeps kFull correctness for composites, skips the
  // per-resolve drain for large framebuffer resolves).
  static int s_nhl_rb_override = -2;  // -2 unresolved, -1 no override, else mode
  if (s_nhl_rb_override == -2) {
    const char* e = std::getenv("NHL_VK_READBACK_MODE");
    s_nhl_rb_override = e ? static_cast<int>(ParseReadbackResolveMode(e)) : -1;
  }
  if (s_nhl_rb_override != -1) {
    return static_cast<ReadbackResolveMode>(s_nhl_rb_override);
  }
  ReadbackResolveMode shared_mode = ParseReadbackResolveMode(REXCVAR_GET(readback_resolve));
  bool shared_mode_overrides_legacy = shared_mode != ReadbackResolveMode::kDisabled ||
                                      rex::cvar::HasNonDefaultValue("readback_resolve");
  if (shared_mode_overrides_legacy) {
    return shared_mode;
  }
  return legacy_readback_resolve_enabled ? ReadbackResolveMode::kFast
                                         : ReadbackResolveMode::kDisabled;
}

