void CommandProcessor::WorkerThreadMain() {
  if (!SetupContext()) {
    rex::FatalError("Unable to setup command processor internal state");
    return;
  }

  uint64_t kicks_since_stall = 0;  // NHL diag (REX_CP_IDLE_STATS)
  while (worker_running_) {
    while (!pending_fns_.empty()) {
      auto fn = std::move(pending_fns_.front());
      pending_fns_.pop();
      fn();
    }

    uint32_t write_ptr_index = write_ptr_index_.load();
    if (write_ptr_index == 0xBAADF00D || read_ptr_index_ == write_ptr_index) {
      SCOPE_profile_cpu_i("gpu", "rex::graphics::CommandProcessor::Stall");
      const auto stall_t0 = std::chrono::steady_clock::now();
      // We've run out of commands to execute.
      // We spin here waiting for new ones, as the overhead of waiting on our
      // event is too high.
      PrepareForWait();
      uint32_t loop_count = 0;
      do {
        // If we spin around too much, revert to a "low-power" state.
        if (loop_count > 500) {
          const int wait_time_ms = 5;
          rex::thread::Wait(write_ptr_index_event_.get(), true,
                            std::chrono::milliseconds(wait_time_ms));
        }

        rex::thread::MaybeYield();
        loop_count++;
        write_ptr_index = write_ptr_index_.load();
      } while (worker_running_ && pending_fns_.empty() &&
               (write_ptr_index == 0xBAADF00D || read_ptr_index_ == write_ptr_index));
      ReturnFromWait();
      // NHL diag (REX_CP_IDLE_STATS=1): time the CP thread sits idle with no new
      // commands from the guest, and how many times per second it ran dry.
      {
        static const bool idle_stats = [] {
          const char* e = std::getenv("REX_CP_IDLE_STATS");
          return e && *e && *e != '0';
        }();
        if (idle_stats) {
          static uint64_t idle_ns = 0, stalls = 0, kicks = 0;
          static auto window_start = std::chrono::steady_clock::now();
          const auto now = std::chrono::steady_clock::now();
          idle_ns += uint64_t(
              std::chrono::duration_cast<std::chrono::nanoseconds>(now - stall_t0).count());
          ++stalls;
          kicks += kicks_since_stall;
          kicks_since_stall = 0;
          const double w = std::chrono::duration<double>(now - window_start).count();
          if (w >= 1.0) {
            REXGPU_INFO("[nhl-cpidle] window={:.2f}s idle={:.1f} ms ({:.0f}%) stalls={} kicks={}",
                        w, idle_ns / 1e6, 100.0 * idle_ns / (w * 1e9), stalls, kicks);
            idle_ns = stalls = kicks = 0;
            window_start = now;
          }
        }
      }
      if (!worker_running_ || !pending_fns_.empty()) {
        continue;
      }
    }
    assert_true(read_ptr_index_ != write_ptr_index);

    // Execute. Note that we handle wraparound transparently.
    ++kicks_since_stall;
    {
      const bool prof = NhlCpProfileEnabled();
      const uint64_t t0 = prof ? NhlNowNs() : 0;
      read_ptr_index_ = ExecutePrimaryBuffer(read_ptr_index_, write_ptr_index);
      if (prof) {
        nhl_cpprof_exec_ns += NhlNowNs() - t0;
        NhlCpProfileMaybeLog();
      }
    }

    // TODO(benvanik): use reader->Read_update_freq_ and only issue after moving
    //     that many indices.
    if (read_ptr_writeback_ptr_) {
      memory::store_and_swap<uint32_t>(memory_->TranslatePhysical(read_ptr_writeback_ptr_),
                                       read_ptr_index_);
    }

    // FIXME: We're supposed to process the WAIT_UNTIL register at this point,
    // but no games seem to actually use it.
  }

  ShutdownContext();
}

void CommandProcessor::Pause() {
  if (paused_) {
    return;
  }
  paused_ = true;

  thread::Fence fence;
  CallInThread([&fence]() {
    fence.Signal();
    thread::Thread::GetCurrentThread()->Suspend();
  });

  fence.Wait();
}

void CommandProcessor::Resume() {
  if (!paused_) {
    return;
  }
  paused_ = false;

  worker_thread_->thread()->Resume();
}

bool CommandProcessor::Save(::rex::stream::ByteStream* stream) {
  assert_true(paused_);

  stream->Write<uint32_t>(primary_buffer_ptr_);
  stream->Write<uint32_t>(primary_buffer_size_);
  stream->Write<uint32_t>(read_ptr_index_);
  stream->Write<uint32_t>(read_ptr_update_freq_);
  stream->Write<uint32_t>(read_ptr_writeback_ptr_);
  stream->Write<uint32_t>(write_ptr_index_.load());

  return true;
}

bool CommandProcessor::Restore(::rex::stream::ByteStream* stream) {
  assert_true(paused_);

  primary_buffer_ptr_ = stream->Read<uint32_t>();
  primary_buffer_size_ = stream->Read<uint32_t>();
  read_ptr_index_ = stream->Read<uint32_t>();
  read_ptr_update_freq_ = stream->Read<uint32_t>();
  read_ptr_writeback_ptr_ = stream->Read<uint32_t>();
  write_ptr_index_.store(stream->Read<uint32_t>());

  return true;
}

